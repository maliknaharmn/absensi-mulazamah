"""Add kitab and timed assignments without changing existing attendance data."""

import os
import sqlite3

from dotenv import load_dotenv

load_dotenv()


def migrate(conn, is_pg, commit=True):
    cur = conn.cursor()

    def has_column(table, column):
        if is_pg:
            cur.execute("""
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = current_schema()
                  AND table_name = %s AND column_name = %s
            """, (table, column))
            return bool(cur.fetchone())
        cur.execute(f"PRAGMA table_info({table})")
        return any(row[1] == column for row in cur.fetchall())

    cur.execute("""
        CREATE TABLE IF NOT EXISTS kitab (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            judul TEXT NOT NULL,
            is_active BOOLEAN NOT NULL DEFAULT TRUE
        )
    """ if is_pg else """
        CREATE TABLE IF NOT EXISTS kitab (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            judul TEXT NOT NULL,
            is_active BOOLEAN NOT NULL DEFAULT TRUE
        )
    """)
    cur.execute("CREATE UNIQUE INDEX IF NOT EXISTS kitab_judul_lower_idx ON kitab (lower(judul))")

    if not has_column("sesi_presensi", "kitab_id"):
        cur.execute("ALTER TABLE sesi_presensi ADD COLUMN kitab_id INTEGER REFERENCES kitab(id)")

    cur.execute("""
        CREATE TABLE IF NOT EXISTS tugas (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            kitab_id INTEGER NOT NULL REFERENCES kitab(id),
            judul TEXT NOT NULL,
            durasi_menit INTEGER NOT NULL CHECK (durasi_menit BETWEEN 1 AND 240),
            token TEXT NOT NULL UNIQUE,
            questions_json TEXT NOT NULL,
            is_active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TEXT NOT NULL
        )
    """ if is_pg else """
        CREATE TABLE IF NOT EXISTS tugas (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            kitab_id INTEGER NOT NULL REFERENCES kitab(id),
            judul TEXT NOT NULL,
            durasi_menit INTEGER NOT NULL CHECK (durasi_menit BETWEEN 1 AND 240),
            token TEXT NOT NULL UNIQUE,
            questions_json TEXT NOT NULL,
            is_active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TEXT NOT NULL
        )
    """)
    if not has_column("tugas", "closes_at"):
        cur.execute("ALTER TABLE tugas ADD COLUMN closes_at TEXT")
    cur.execute("""
        CREATE TABLE IF NOT EXISTS tugas_akses (
            tugas_id INTEGER NOT NULL REFERENCES tugas(id),
            peserta_id INTEGER NOT NULL REFERENCES peserta(id),
            allowed BOOLEAN NOT NULL,
            closes_at TEXT,
            PRIMARY KEY (tugas_id, peserta_id)
        )
    """)
    cur.execute("""
        CREATE TABLE IF NOT EXISTS percobaan_tugas (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            tugas_id INTEGER NOT NULL REFERENCES tugas(id),
            peserta_id INTEGER NOT NULL REFERENCES peserta(id),
            attempt_token TEXT NOT NULL UNIQUE,
            started_at TEXT NOT NULL,
            deadline_at TEXT NOT NULL,
            submitted_at TEXT,
            reviewed_at TEXT,
            answers_json TEXT NOT NULL DEFAULT '{}',
            UNIQUE (tugas_id, peserta_id)
        )
    """ if is_pg else """
        CREATE TABLE IF NOT EXISTS percobaan_tugas (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            tugas_id INTEGER NOT NULL REFERENCES tugas(id),
            peserta_id INTEGER NOT NULL REFERENCES peserta(id),
            attempt_token TEXT NOT NULL UNIQUE,
            started_at TEXT NOT NULL,
            deadline_at TEXT NOT NULL,
            submitted_at TEXT,
            reviewed_at TEXT,
            answers_json TEXT NOT NULL DEFAULT '{}',
            UNIQUE (tugas_id, peserta_id)
        )
    """)
    if commit:
        conn.commit()


if __name__ == "__main__":
    if os.environ.get("DATABASE_URL"):
        import psycopg2
        conn = psycopg2.connect(os.environ.get("DATABASE_URL_UNPOOLED") or os.environ["DATABASE_URL"])
        is_pg = True
    else:
        db_path = os.path.join(os.path.dirname(__file__), "instance", "absensi.db")
        conn = sqlite3.connect(db_path)
        conn.execute("PRAGMA foreign_keys = ON")
        is_pg = False
    try:
        migrate(conn, is_pg)
        print("MVP schema ready")
    finally:
        conn.close()
